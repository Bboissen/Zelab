#!/usr/bin/env python3
"""Create config/site.yaml once from facts discovered on this host.

Only values that differ per host are written; everything else comes from
config/defaults.yaml. Existing site inputs are retained.
"""

import argparse
import datetime
import ipaddress
import os
from pathlib import Path
import pwd

import shell


ROOT = Path(__file__).resolve().parents[1]
TAIL_ROUTES = ("ui_tail_hermes_port", "ui_tail_paperclip_port", "ui_tail_obsidian_port")
TAIL_DEFAULTS = (443, 8443, 9443)
TAIL_SPARES = (8444, 9444, 10443, 10444, 11443, 11444)


def probe(argv):
    """Return command output, or None. Never print it: it can contain host details."""
    return shell.output(argv, timeout=20)


def operator():
    if os.geteuid() == 0:
        name = os.environ.get("SUDO_USER")
        if not name or name == "root":
            raise SystemExit("Run as your normal (non-root) account.")
        return name
    return pwd.getpwuid(os.getuid()).pw_name


def tailnet(status_json):
    running, name = shell.tailnet_name(shell.load_json(status_json))
    return name if running and name and name.endswith(".ts.net") else None


def choose_tail_ports(serve, owned_backends):
    """Pick the default Serve ports unless another route already uses them.

    A port already forwarding to this site's own backend is reused, so rerunning
    discovery after installation keeps the same URLs.
    """
    config = shell.load_json(serve)
    ours = {}
    for _, port, backend in shell.serve_routes(config):
        if backend in owned_backends:
            ours[owned_backends[backend]] = port
    used = {int(port) for port in (config.get("TCP") or {})} - set(ours.values())
    chosen = {}
    for name, default in zip(TAIL_ROUTES, TAIL_DEFAULTS):
        if name in ours:
            chosen[name] = ours[name]
            continue
        taken = used | set(chosen.values()) | set(ours.values())
        chosen[name] = next(p for p in (default, *TAIL_SPARES) if p not in taken)
    return chosen


def ssh_listener(effective):
    """Choose the existing host SSH listener that project host accounts will use."""
    ports, addresses = [], []
    for line in (effective or "").splitlines():
        key, _, value = line.partition(" ")
        if key == "port":
            ports.append(int(value))
        elif key == "listenaddress":
            host, _, port = value.rpartition(":")
            addresses.append((host.strip("[]"), int(port)))
    for host, port in addresses:
        if host in ("0.0.0.0", "127.0.0.1", "::", "::1"):
            return "127.0.0.1", port
    for host, port in addresses:
        try:
            address = ipaddress.ip_address(host)
        except ValueError:
            continue
        if address.version == 4 and address not in ipaddress.ip_network("100.64.0.0/10"):
            return host, port
    return "127.0.0.1", ports[0] if ports else 22


def discover(user):
    defaults = {"guest_dashboard_port": 18640, "paperclip_port": 13100, "obsidian_backend_port": 18645}
    facts = {"operator_user": user}
    hostname = tailnet(probe(["tailscale", "status", "--json"]))
    facts["ui_tailscale_enabled"] = hostname is not None
    if hostname:
        facts["ui_tailscale_hostname"] = hostname
        backends = {f"http://127.0.0.1:{defaults[key]}": route for key, route in
                    zip(defaults, TAIL_ROUTES)}
        facts.update(choose_tail_ports(probe(["tailscale", "serve", "status", "--json"]), backends))
    effective = probe(["sudo", "-n", "/usr/sbin/sshd", "-T", "-C",
                       f"user={user},host=localhost,addr=127.0.0.1,laddr=127.0.0.1,lport=22"])
    facts["worker_ssh_host"], facts["worker_ssh_port"] = ssh_listener(effective)
    facts["_ssh_discovered"] = effective is not None
    return facts


def render(facts, today):
    lines = [
        f"# Generated by `make` on {today} from this host's discovered settings.",
        "# Other values come from config/defaults.yaml; add a key here to override one.",
        "# Edit, then rerun: make",
        "",
        f"operator_user: {facts['operator_user']}",
        "",
        "# Existing host SSH listener Paperclip uses to reach project host accounts.",
        f"worker_ssh_host: {facts['worker_ssh_host']}",
        f"worker_ssh_port: {facts['worker_ssh_port']}",
        "",
    ]
    if facts["ui_tailscale_enabled"]:
        lines += ["# Private HTTPS through Tailscale Serve (ports chosen to avoid existing routes).",
                  "ui_tailscale_enabled: true",
                  f"ui_tailscale_hostname: {facts['ui_tailscale_hostname']}"]
        lines += [f"{name}: {facts[name]}" for name in TAIL_ROUTES]
    else:
        lines += ["# Tailscale was not running. UIs stay on localhost until you enroll this",
                  "# host, then set ui_tailscale_enabled: true and ui_tailscale_hostname.",
                  "ui_tailscale_enabled: false"]
    lines.append("")
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--site-config", type=Path, default=ROOT / "config/site.yaml")
    parser.add_argument("--env-file", type=Path, default=ROOT / ".env")
    args = parser.parse_args(argv)
    if args.site_config.exists() or args.site_config.is_symlink():
        return 0
    facts = discover(operator())
    text = render(facts, datetime.date.today().isoformat())
    args.site_config.parent.mkdir(parents=True, exist_ok=True)
    with os.fdopen(os.open(args.site_config, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600), "w") as output:
        output.write(text)
    print(f"Created {args.site_config} from this host:")
    print(f"  operator: {facts['operator_user']}")
    print(f"  host SSH listener: {facts['worker_ssh_host']}:{facts['worker_ssh_port']}"
          + ("" if facts["_ssh_discovered"] else " (default; sshd settings were not readable)"))
    if facts["ui_tailscale_enabled"]:
        urls = ", ".join(str(facts[name]) for name in TAIL_ROUTES)
        print(f"  tailnet: {facts['ui_tailscale_hostname']} (HTTPS ports {urls})")
    else:
        print("  tailnet: not running; UIs will be localhost-only for now")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError) as error:
        raise SystemExit(str(error)) from None
