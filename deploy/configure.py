#!/usr/bin/env python3
"""Create config/site.yaml once from facts discovered on this host.

Only values that differ per host are written; everything else comes from
config/defaults.yaml. Existing site inputs are retained; interactive harness
selection updates only worker_harness when the installer invokes --select-harness.
"""

import argparse
import datetime
import ipaddress
import json
import os
from pathlib import Path
import pwd
import subprocess
import sys

from console import heading, paint


ROOT = Path(__file__).resolve().parents[1]
TAIL_ROUTES = ("ui_tail_hermes_port", "ui_tail_paperclip_port", "ui_tail_obsidian_port")
TAIL_DEFAULTS = (443, 8443, 9443)
TAIL_SPARES = (8444, 9444, 10443, 10444, 11443, 11444)


def probe(argv):
    """Return command output, or None. Never print it: it can contain host details."""
    try:
        result = subprocess.run(["rtk", "proxy", *argv], capture_output=True, text=True, timeout=20)
    except (OSError, subprocess.TimeoutExpired):
        return None
    return result.stdout if result.returncode == 0 else None


def operator():
    if os.geteuid() == 0:
        name = os.environ.get("SUDO_USER")
        if not name or name == "root":
            raise SystemExit("Run as your normal (non-root) account.")
        return name
    return pwd.getpwuid(os.getuid()).pw_name


def tailnet(status_json):
    try:
        status = json.loads(status_json or "")
        name = status["Self"]["DNSName"].rstrip(".")
    except (ValueError, KeyError, TypeError, AttributeError):
        return None
    return name if status.get("BackendState") == "Running" and name.endswith(".ts.net") else None


def serve_ports(serve, owned_backends):
    """Pick the default Serve ports unless another route already uses them.

    A port already proxying to this site's own backend is reused, so rerunning
    discovery after installation keeps the same URLs.
    """
    try:
        config = json.loads(serve or "{}") or {}
    except ValueError:
        config = {}
    ours = {}
    for endpoint, web in (config.get("Web") or {}).items():
        port = int(endpoint.rsplit(":", 1)[1])
        proxy = ((web.get("Handlers") or {}).get("/") or {}).get("Proxy")
        if proxy in owned_backends:
            ours[owned_backends[proxy]] = port
    used = {int(port) for port in (config.get("TCP") or {})} - set(ours.values())
    chosen = {}
    for name, default in zip(TAIL_ROUTES, TAIL_DEFAULTS):
        if name in ours:
            chosen[name] = ours[name]
            continue
        taken = used | set(chosen.values()) | set(ours.values())
        chosen[name] = next(p for p in (default, *TAIL_SPARES) if p not in taken)
    return chosen


def ssh_listener(effective):
    """Choose the existing host SSH listener that local workers will use."""
    ports, addresses = [], []
    for line in (effective or "").splitlines():
        key, _, value = line.partition(" ")
        if key == "port":
            ports.append(int(value))
        elif key == "listenaddress":
            host, _, port = value.rpartition(":")
            addresses.append((host.strip("[]"), int(port)))
    for host, port in addresses:
        if host in ("0.0.0.0", "127.0.0.1", "::", "::1"):
            return "127.0.0.1", port
    for host, port in addresses:
        try:
            address = ipaddress.ip_address(host)
        except ValueError:
            continue
        if address.version == 4 and address not in ipaddress.ip_network("100.64.0.0/10"):
            return host, port
    return "127.0.0.1", ports[0] if ports else 22


def discover(user):
    defaults = {"guest_dashboard_port": 18640, "paperclip_port": 13100, "obsidian_backend_port": 18645}
    facts = {"operator_user": user}
    hostname = tailnet(probe(["tailscale", "status", "--json"]))
    facts["ui_tailscale_enabled"] = hostname is not None
    if hostname:
        facts["ui_tailscale_hostname"] = hostname
        backends = {f"http://127.0.0.1:{defaults[key]}": route for key, route in
                    zip(defaults, TAIL_ROUTES)}
        facts.update(serve_ports(probe(["tailscale", "serve", "status", "--json"]), backends))
    effective = probe(["sudo", "-n", "/usr/sbin/sshd", "-T", "-C",
                       f"user={user},host=localhost,addr=127.0.0.1,laddr=127.0.0.1,lport=22"])
    facts["worker_ssh_host"], facts["worker_ssh_port"] = ssh_listener(effective)
    facts["_ssh_discovered"] = effective is not None
    return facts


def render(facts, today):
    lines = [
        f"# Generated by `rtk proxy make` on {today} from this host's discovered settings.",
        "# Other values come from config/defaults.yaml; add a key here to override one.",
        "# Edit, then rerun: rtk proxy make",
        "",
        f"operator_user: {facts['operator_user']}",
        "",
        "# Existing host SSH listener used by local Paperclip workers.",
        f"worker_ssh_host: {facts['worker_ssh_host']}",
        f"worker_ssh_port: {facts['worker_ssh_port']}",
        "",
    ]
    if facts["ui_tailscale_enabled"]:
        lines += ["# Private HTTPS through Tailscale Serve (ports chosen to avoid existing routes).",
                  "ui_tailscale_enabled: true",
                  f"ui_tailscale_hostname: {facts['ui_tailscale_hostname']}"]
        lines += [f"{name}: {facts[name]}" for name in TAIL_ROUTES]
    else:
        lines += ["# Tailscale was not running. UIs stay on localhost until you enroll this",
                  "# host, then set ui_tailscale_enabled: true and ui_tailscale_hostname.",
                  "ui_tailscale_enabled: false"]
    lines += [
        "",
        "# Discord: needed before the first Discord test, not for installation.",
        "# Enable Developer Mode in Discord, then right-click to Copy ID.",
        "discord_owner_id: ''      # your numeric Discord user ID",
        "discord_channel_id: ''    # a private test channel for Research",
        "",
    ]
    return "\n".join(lines)


def select_harness(site_path):
    """Offer the saved choice on each terminal run; retain unattended inputs."""
    import yaml
    from run import load_yaml
    site = load_yaml(site_path)
    saved = site.get('worker_harness', 'none')
    if saved not in ('codex', 'claude', 'both', 'none'):
        raise ValueError('worker_harness must be codex, claude, both or none')
    choice = saved
    labels = {'codex': 'Codex', 'claude': 'Claude Code', 'both': 'Codex + Claude Code', 'none': 'skipped'}
    if sys.stdin.isatty():
        heading('Optional Paperclip worker harness')
        print('  1. Codex\n  2. Claude Code\n  3. Both\n  4. Skip for now')
        print('  Selected CLIs are installed for workers. Sign in using their native login.')
        print('  Skip leaves new workers paused; existing Paperclip settings are retained.')
        print('  Both installs both CLIs; choose each worker adapter in Paperclip before resuming.')
        print(f'  Current selection: {labels[saved]}')
        choices = {'1': 'codex', 'codex': 'codex', '2': 'claude', 'claude': 'claude',
                   'claude code': 'claude', '3': 'both', 'both': 'both',
                   '4': 'none', 'none': 'none', 'skip': 'none', '': saved}
        default = {'codex': 1, 'claude': 2, 'both': 3, 'none': 4}[saved]
        while True:
            answer = input(f'  Choose [1/2/3/4, default {default}]: ').strip().lower()
            if answer in choices:
                choice = choices[answer]
                break
            print('  Enter 1 (Codex), 2 (Claude Code), 3 (both), or 4 (skip).')
    # Replace only the value, keeping comments, permissions and unrelated inputs.
    if 'worker_harness' not in site:
        with site_path.open('a') as output:
            output.write(f'\n# Optional Paperclip harness: codex, claude, both or none.\nworker_harness: {choice}\n')
    elif choice != saved:
        original = site_path.read_text()
        document = yaml.compose(original)
        value = next(value for key, value in document.value if key.value == 'worker_harness')
        start, end = value.start_mark.index, value.end_mark.index
        if original[start:end] not in (saved, f"'{saved}'", f'"{saved}"'):
            raise ValueError('Use a direct worker_harness scalar in the site file before changing this selection')
        site_path.write_text(original[:start] + choice + original[end:])
    print(f'  Paperclip worker harness: {paint(labels[choice], "bold")} (saved in {site_path})')


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--site-config", type=Path, default=ROOT / "config/site.yaml")
    parser.add_argument('--select-harness', action='store_true')
    args = parser.parse_args(argv)
    if args.select_harness:
        select_harness(args.site_config)
        return 0
    if args.site_config.exists() or args.site_config.is_symlink():
        return 0
    facts = discover(operator())
    text = render(facts, datetime.date.today().isoformat())
    args.site_config.parent.mkdir(parents=True, exist_ok=True)
    with os.fdopen(os.open(args.site_config, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600), "w") as output:
        output.write(text)
    print(f"Created {args.site_config} from this host:")
    print(f"  operator: {facts['operator_user']}")
    print(f"  worker SSH listener: {facts['worker_ssh_host']}:{facts['worker_ssh_port']}"
          + ("" if facts["_ssh_discovered"] else " (default; sshd settings were not readable)"))
    if facts["ui_tailscale_enabled"]:
        urls = ", ".join(str(facts[name]) for name in TAIL_ROUTES)
        print(f"  tailnet: {facts['ui_tailscale_hostname']} (HTTPS ports {urls})")
    else:
        print("  tailnet: not running; UIs will be localhost-only for now")
    print("  Discord IDs: pending (only needed before the first Discord test)")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError) as error:
        raise SystemExit(str(error)) from None
